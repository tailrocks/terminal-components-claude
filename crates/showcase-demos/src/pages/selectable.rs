use termrock::author::PaintStyle;
use termrock::{Color, Modifier, Rect, Ui, width};

pub fn paint(ui: &mut Ui<'_>, area: Rect) {
    if area.width < 94 || area.height < 36 {
        return;
    }
    for (offset, row) in ROWS.iter().enumerate() {
        let Ok(dy) = u16::try_from(offset) else {
            break;
        };
        let y = area.y.saturating_add(dy);
        if y >= area.bottom() {
            break;
        }
        let mut x = area.x;
        for run in *row {
            let columns = width(run.text);
            let room = area.right().saturating_sub(x);
            if room == 0 {
                break;
            }
            ui.paint_str(
                Rect::new(x, y, columns.min(room), 1),
                run.text,
                ink(run.fg, run.bg, run.bold, run.under, run.dim),
            );
            x = x.saturating_add(columns);
        }
    }
}

fn ink(fg: u32, bg: u32, bold: bool, under: bool, dim: bool) -> PaintStyle {
    let mut style = PaintStyle::new()
        .fg(Color::from_u32(fg))
        .bg(Color::from_u32(bg))
        .remove_modifier(Modifier::all());
    if bold {
        style = style.add_modifier(Modifier::BOLD);
    }
    if under {
        style = style.add_modifier(Modifier::UNDERLINED);
    }
    if dim {
        style = style.add_modifier(Modifier::DIM);
    }
    style
}

