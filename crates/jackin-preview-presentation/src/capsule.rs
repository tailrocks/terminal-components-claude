pub fn paint_paused_capsule(buf: &mut Buffer) {
    for run in RUNS {
        let mut style = Style::new()
            .fg(Color::from_u32(run.fg))
            .bg(Color::from_u32(run.bg));
        if run.bold {
            style = style.add_modifier(Modifier::BOLD);
        }
        if run.italic {
            style = style.add_modifier(Modifier::ITALIC);
        }
        let mut x = run.x;
        for ch in run.text.chars() {
            put(buf, x, run.y, ch, style);
            x = x.saturating_add(1);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use termrock::Rect;

    #[test]
    fn paused_frame_covers_the_tag_capsule() {
        let area = Rect::new(0, 0, 120, 40);
        let mut buf = Buffer::empty(area);
        paint_paused_capsule(&mut buf);
        let mark = buf.cell((2, 0)).expect("brand");
        assert_eq!(mark.symbol(), "j");
        assert!(mark.modifier.contains(Modifier::BOLD));
        assert_eq!(mark.bg, Color::from_u32(0x48_e0_54));
        let tab = (0..16)
            .map(|x| buf.cell((x, 2)).expect("tab").symbol())
            .collect::<String>();
        assert!(tab.contains("Mix"), "{tab}");
        let pct = buf.cell((114, 38)).expect("usage");
        assert_eq!(pct.symbol(), "7");
        assert!(pct.modifier.contains(Modifier::ITALIC));
    }
}
