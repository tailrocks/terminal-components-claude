pub fn paint_paused_launch_running(buf: &mut Buffer) {
    for run in RUNS {
        let mut style = Style::new()
            .fg(Color::from_u32(run.fg))
            .bg(Color::from_u32(run.bg));
        if run.bold {
            style = style.add_modifier(Modifier::BOLD);
        }
        let mut x = run.x;
        for ch in run.text.chars() {
            put(buf, x, run.y, ch, style);
            x = x.saturating_add(1);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use termrock::Rect;

    #[test]
    fn paused_frame_covers_the_tag_cockpit() {
        let area = Rect::new(0, 0, 120, 40);
        let mut buf = Buffer::empty(area);
        paint_paused_launch_running(&mut buf);
        let mark = buf.cell((1, 0)).expect("brand");
        assert_eq!(mark.symbol(), " ");
        assert_eq!(mark.bg, Color::from_u32(0x48_e0_54));
        let letter = buf.cell((2, 0)).expect("j");
        assert_eq!(letter.symbol(), "j");
        assert!(letter.modifier.contains(Modifier::BOLD));
        let stage = (0..120)
            .map(|x| buf.cell((x, 6)).expect("stage").symbol())
            .collect::<String>();
        assert!(stage.contains("Credentials"), "{stage}");
    }
}
