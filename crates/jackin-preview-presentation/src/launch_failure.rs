pub fn paint_paused_launch_failure(buf: &mut Buffer, theme: &Theme) {
    let full = Rect::new(0, 0, 120, 40);
    let base = Style::new()
        .fg(Color::from_u32(0x00ff_ffff))
        .bg(Color::from_u32(0x0000_0000));
    for y in full.y..full.bottom() {
        for x in full.x..full.right() {
            put(buf, x, y, ' ', base);
        }
    }
    let body = Rect::new(0, 2, 120, 36);
    let exclude = [Rect::new(36, 3, 48, 17), Rect::new(0, 35, 120, 3)];
    paint_atmosphere(buf, body, &exclude, FROZEN_TICK, false, true, theme);
    let muted = Style::new()
        .fg(Color::from_u32(0x008a_8a8a))
        .bg(Color::from_u32(0x0000_0000));
    for y in 0..39 {
        for x in 0..120 {
            let Some(cell) = buf.cell_mut(termrock::Position::new(x, y)) else {
                continue;
            };
            if cell.fg == Color::from_u32(0x00ff_ffff) && cell.bg == Color::from_u32(0x0000_0000) {
                cell.set_style(muted);
            }
        }
    }
    for ink in INK {
        let mut style = Style::new()
            .fg(Color::from_u32(ink.fg))
            .bg(Color::from_u32(ink.bg));
        if ink.bold {
            style = style.add_modifier(Modifier::BOLD);
        }
        let mut x = ink.x;
        for ch in ink.text.chars() {
            put(buf, x, ink.y, ch, style);
            x = x.saturating_add(1);
        }
    }
}
