pub(super) fn paint(ui: &mut Ui<'_>) {
    for run in RUNS {
        let style = PaintStyle::new()
            .fg(Color::from_u32(run.fg))
            .bg(Color::from_u32(run.bg));
        let style = if run.bold {
            style.add_modifier(Modifier::BOLD)
        } else {
            style.remove_modifier(Modifier::BOLD)
        };
        ui.paint_str(
            termrock::Rect {
                x: run.x,
                y: run.y,
                width: u16::try_from(run.text.chars().count()).unwrap_or(0),
                height: 1,
            },
            run.text,
            style,
        );
    }
}
