pub(super) fn paint(ui: &mut Ui<'_>) {
    for run in RUNS {
        let mut style = PaintStyle::new()
            .fg(Color::from_u32(run.fg))
            .bg(Color::from_u32(run.bg));
        style = if run.bold {
            style.add_modifier(Modifier::BOLD)
        } else {
            style.remove_modifier(Modifier::BOLD)
        };
        let Ok(width) = u16::try_from(run.text.chars().count()) else {
            continue;
        };
        if width > 0 {
            ui.paint_str(Rect::new(run.x, run.y, width, 1), run.text, style);
        }
    }
}
