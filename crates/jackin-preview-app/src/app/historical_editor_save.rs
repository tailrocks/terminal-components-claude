pub(super) fn paint(ui: &mut Ui<'_>) {
    for run in RUNS {
        let mut style = PaintStyle::new();
        style = match run.fg {
            Some(fg) => style.fg(Color::from_u32(fg)),
            None => style.fg(Color::Reset),
        };
        style = match run.bg {
            Some(bg) => style.bg(Color::from_u32(bg)),
            None => style.bg(Color::Reset),
        };
        style = if run.bold {
            style.add_modifier(Modifier::BOLD)
        } else {
            style.remove_modifier(Modifier::BOLD)
        };
        style = if run.underline {
            style.add_modifier(Modifier::UNDERLINED)
        } else {
            style.remove_modifier(Modifier::UNDERLINED)
        };
        let Ok(width) = u16::try_from(run.text.chars().count()) else {
            continue;
        };
        if width > 0 {
            ui.paint_str(Rect::new(run.x, run.y, width, 1), run.text, style);
        }
    }
}
