pub(super) fn paint(ui: &mut Ui<'_>, area: Rect) {
    for run in RUNS {
        let width = u16::try_from(run.text.chars().count()).unwrap_or(0);
        let mut style = PaintStyle::new()
            .fg(Color::from_u32(run.fg))
            .bg(Color::from_u32(0));
        if run.bold {
            style = style.add_modifier(Modifier::BOLD);
        }
        ui.paint_str(
            Rect::new(
                area.x.saturating_add(run.x),
                area.y.saturating_add(run.y),
                width,
                1,
            ),
            run.text,
            style,
        );
    }
}

#[cfg(test)]
mod tests {
    use super::RUNS;

    #[test]
    fn runs_cover_the_frame_once() {
        let mut seen = [false; 120 * 40];
        for run in RUNS {
            let mut x = usize::from(run.x);
            let y = usize::from(run.y);
            for _ in run.text.chars() {
                let index = y * 120 + x;
                assert!(!seen[index], "overlap at {x},{y}");
                seen[index] = true;
                x = x.saturating_add(1);
            }
            assert_eq!(x, usize::from(run.x) + run.text.chars().count());
        }
        assert!(seen.iter().all(|cell| *cell));
    }
}
