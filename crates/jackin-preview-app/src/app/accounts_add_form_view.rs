pub(super) fn paint(ui: &mut Ui<'_>) {
    for &(x, y, text, fg, bg, bold, italic) in ENTRIES {
        let mut style = PaintStyle::new()
            .fg(Color::from_u32(fg))
            .bg(Color::from_u32(bg));
        if bold {
            style = style.add_modifier(Modifier::BOLD);
        } else {
            style = style.remove_modifier(Modifier::BOLD);
        }
        if italic {
            style = style.add_modifier(Modifier::ITALIC);
        } else {
            style = style.remove_modifier(Modifier::ITALIC);
        }
        let mut col = x;
        for ch in text.chars() {
            let mut buf = [0u8; 4];
            ui.paint_cell(Position::new(col, y), ch.encode_utf8(&mut buf), style);
            col = col.saturating_add(1);
        }
    }
}
