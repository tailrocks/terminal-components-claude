pub(super) fn paint(ui: &mut Ui<'_>) {
    for run in RUNS {
        let mut on = Modifier::empty();
        if run.bold {
            on = on.union(Modifier::BOLD);
        }
        if run.italic {
            on = on.union(Modifier::ITALIC);
        }
        if run.under {
            on = on.union(Modifier::UNDERLINED);
        }
        // paint_str clears modifiers that are off.
        let mut style = PaintStyle::new()
            .fg(Color::from_u32(run.fg))
            .bg(Color::from_u32(run.bg))
            .remove_modifier(Modifier::all().difference(on));
        if !on.is_empty() {
            style = style.add_modifier(on);
        }
        let Ok(width) = u16::try_from(run.text.chars().count()) else {
            continue;
        };
        if width > 0 {
            ui.paint_str(Rect::new(run.x, run.y, width, 1), run.text, style);
        }
    }
}
