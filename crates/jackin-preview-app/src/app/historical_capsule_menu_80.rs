pub(super) fn paint(ui: &mut Ui<'_>) {
    for run in RUNS {
        let mut on = Modifier::empty();
        if run.bold {
            on = on.union(Modifier::BOLD);
        }
        if run.italic {
            on = on.union(Modifier::ITALIC);
        }
        // A clipped popup restarts paint_str at the clip edge. Paint each cell
        // at its own position, and clear modifiers the stamp does not set.
        let mut style = PaintStyle::new()
            .fg(Color::from_u32(run.fg))
            .bg(Color::from_u32(run.bg))
            .remove_modifier(Modifier::all());
        if !on.is_empty() {
            style = style.add_modifier(on);
        }
        let mut x = run.x;
        for ch in run.text.chars() {
            let mut buf = [0u8; 4];
            ui.paint_cell(Position::new(x, run.y), ch.encode_utf8(&mut buf), style);
            x = x.saturating_add(1);
        }
    }
}
