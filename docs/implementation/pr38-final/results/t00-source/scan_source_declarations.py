def fence_records(lines, opener, path, rustdoc=False):
    """Pair documentation and Markdown fences without letting their bodies alter tags."""
    found=[]; active=None
    for index,line in enumerate(lines,1):
        match=opener.match(line)
        if active is None:
            if not match: continue
            marker=match.group(1); info=match.group(2).strip()
            tags=[x.strip() for x in re.split(r'[,\s]+',info) if x.strip()]
            langtag=tags[0] if tags else ('rust-default' if rustdoc else 'unlabeled')
            active={'path':path,'line':index,'fence':info,'marker':marker,'tags':tags,'assumed_language':langtag,
                    'ignored':any(x in {'ignore','no_run','text'} for x in tags) or langtag=='text',
                    'status':'rustdoc-fence-candidate' if rustdoc else 'Markdown code-block candidate'}
        elif match:
            marker=match.group(1); info=match.group(2).strip()
            if marker[0]==active['marker'][0] and len(marker)>=len(active['marker']) and not info.strip():
                active['close_line']=index
                active['body_line_count']=max(0,index-active['line']-1)
                found.append(active); active=None
    if active is not None:
        active['close_line']=None; active['body_line_count']=None; active['pairing']='unclosed fence in scanned source'
        found.append(active)
    return found

def matching_brace(source, opening):
    """Return the matching brace while skipping comments and quoted strings."""
    depth=0; i=opening; state='normal'; block_depth=0; raw_end=None
    while i<len(source):
        c=source[i]; nxt=source[i+1] if i+1<len(source) else ''
        if state=='line':
            if c=='\n': state='normal'
        elif state=='block':
            if c=='/' and nxt=='*': block_depth+=1; i+=1
            elif c=='*' and nxt=='/': block_depth-=1; i+=1; state='normal' if block_depth==0 else 'block'
        elif state=='string':
            if c=='\\': i+=1
            elif c=='"': state='normal'
        elif state=='char':
            if c=='\\': i+=1
            elif c=='\'': state='normal'
        elif state=='raw':
            if c=='"' and source.startswith('#'*(raw_end or 0),i+1):
                i+=(raw_end or 0); state='normal'
        else:
            if c=='/' and nxt=='/': state='line'; i+=1
            elif c=='/' and nxt=='*': state='block'; block_depth=1; i+=1
            elif c=='b' and nxt=='"': state='string'; i+=2; continue
            elif c=='r' or (c=='b' and nxt in {'r','"'}):
                j=i+(2 if c=='b' else 1)
                if j<len(source) and source[j]=='#':
                    while j<len(source) and source[j]=='#': j+=1
                if j<len(source) and source[j]=='"':
                    raw_end=j-(i+(2 if c=='b' else 1)); state='raw'; i=j
                elif j<len(source) and source[j]=='"': state='string'; i=j
            elif c=='"': state='string'
            elif c=='\'' and i+2<len(source):
                # A short quoted character is distinct from a Rust lifetime.
                end=source.find('\'',i+1,min(len(source),i+8))
                if end!=-1 and '\n' not in source[i:end]: state='char'; i+=1; continue
            elif c=='{': depth+=1
            elif c=='}':
                depth-=1
                if depth==0: return i+1
        i+=1
    return None

